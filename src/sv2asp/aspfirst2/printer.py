# totality certificate for guarded heads
# ---------------------------------------------------------------------------------------------

def _domain(d: Design, sig: str, rules: list):
    """The set of values `sig` ranges over for the coverage question of these rules, as clingo
    text, or None when it cannot be bounded (a wide signal under an ordering compare)."""
    w = d.width_of(sig)
    if isinstance(w, tuple):
        return "; ".join(l for l, _ in d.enums[w[1]])
    consts, ordered = set(), False
    for r in rules:
        for s, c in r.guards:
            if s == sig:
                consts.add(c)
        var_sig = {v: s for s, v in r.reads}
        for v, op, c in r.cmps:
            if var_sig[v] == sig:
                consts.add(c)
                if op in ("<", ">", "<=", ">="):
                    ordered = True
    if w <= 10 and (ordered or not consts or w <= 4):
        return f"0..{2 ** w - 1}"
    if ordered:
        return None
    ints = sorted(c for c in consts if isinstance(c, int))
    fresh = next(i for i in range(2 ** w) if i not in ints)   # one value none of the arms name
    return "; ".join(str(c) for c in ints + [fresh])


def totality_certificate(d: Design, head: str, clingo: str | None = None) -> bool:
    """True iff the head's arms are PROVEN to cover every valuation of the signals they guard on
    (each free over its domain, independently -- an over-approximation, so True is safe)."""
    from .lint import clingo_bin
    rules = [r for r in d.rules if r.head == head]
    sigs = sorted({s for r in rules for s, _ in r.guards} | {s for r in rules for s, _ in r.reads})
    prog = []
    for s in sigs:
        dom = _domain(d, s, rules)
        if dom is None:
            return False
        prog.append(f"{{ val({s}, V, 0) : V = ({dom}) }} = 1.")
    prog.append("time(clk, 0).")
    for r in rules:
        prog.append(r.text + ".")
    prog.append(f"gap :- not val({head}, _, 0).")
    prog.append(":- not gap.")
    with tempfile.TemporaryDirectory() as td:
        f = pathlib.Path(td) / "cover.lp"
        f.write_text("\n".join(prog) + "\n")
        p = subprocess.run([clingo or clingo_bin(), "-q", str(f), str(LIB_DIR / "aspfirst.lp")],
                           capture_output=True, text=True, timeout=120)
    return "UNSATISFIABLE" in p.stdout


