class PrintError(Exception):
    pass


#: the operators printed as ONE SV binary operator between two leaves (module-level so a test can
#: sabotage one and prove the round trip notices)
BIN_OPS = {"add": "+", "sub": "-", "mul": "*", "and": "&", "or": "|", "xor": "^",
           "shl": "<<", "shr": ">>", "idiv": "/", "imod": "%",
           "lt": "<", "le": "<=", "gt": ">", "ge": ">=", "eq": "==", "ne": "!=",
           # logand/logor print BITWISE: the authoring nets are 1-bit, where & and | are
           # the same functions -- and the round-trip translator's lane machinery lowers
           # bitwise trees where a &&-tree on a lane target is a named refusal (found by
           # the regeneration run's human-shaped print, 2026-08-31)
           "logand": "&", "logor": "|"}


