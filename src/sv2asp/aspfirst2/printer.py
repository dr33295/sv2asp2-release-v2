class _Ctx:
    """Per-net SSA emission context: hoisted wires + their assigns."""

    def __init__(self, d: Design, lhs: str, axes_txt: tuple | None = None, gv: tuple | None = None):
        self.d, self.lhs, self.n = d, lhs, 0
        self.decls: list = []
        self.assigns: list = []
        self._memo: dict = {}
        # a MULTI-AXIS generate: a hoisted wire is declared at MODULE level as a lane over the
        # same axes and assigned per position, because a declaration inside a NESTED
        # for-generate body is one the translator refuses (2026-09-03); `decls` then go
        # before the generate block, not inside it
        self.axes_txt, self.gv = axes_txt, gv

    def wire(self, w, rhs: str) -> str:
        """A hoisted wire for `rhs` at width w (the same rhs at the same width is one wire)."""
        key = (str(w), rhs)
        if key in self._memo:
            return self._memo[key]
        name = f"{_sv_ident(self.lhs)}__e{self.n}"
        self.n += 1
        if self.axes_txt:
            dims = "".join(f"[{a}-1:0]" if not a.isdigit() else f"[{int(a) - 1}:0]" for a in self.axes_txt)
            elem = _wdecl(w)[len("logic "):]
            idx = "".join(f"[{g}]" for g in self.gv)
            self.decls.append(f"  logic {dims}{elem} {name};")
            self.assigns.append(f"    assign {name}{idx} = {rhs};")
            self._memo[key] = name + idx
            return name + idx
        self.decls.append(f"  {_wdecl(w)} {name};")
        self.assigns.append(f"  assign {name} = {rhs};")
        self._memo[key] = name
        return name

    def leaf(self, t) -> str:
        """The text of `t` as a leaf: a net name, a sized literal, a tag, or a hoisted wire.
        Boolean nodes and muxes INLINE with parentheses instead of hoisting a wire -- a
        1-bit && / || / ! has no width subtleties for the SSA machinery to guard, and an
        ite's arms keep their own handling; this is what turns `x__e0` chains into the
        readable `a[i] ? v : (hold)` shape (the regeneration run's naming requirement)."""
        if isinstance(t, tuple) and t and t[0] in (
                "logand", "logor", "lnot", "ite",
                "eq", "ne", "lt", "le", "gt", "ge", "slt", "sle", "sgt", "sge"):
            if t[0] != "logand" and t[0] != "logor" and t[0] != "lnot":
                return "(" + self.expr(t) + ")"
            if width_of(self.d, t) == 1:
                return "(" + self.expr(t) + ")"
        if isinstance(t, str):
            lm = _lane_member(self.d, t)
            if lm is not None:
                return _sv_ref(lm)
            return t
        if t[0] == "k":
            v, w = t[1], t[2]
            wide = isinstance(v, tuple) and v[0] == "str"            # a wide constant: ("str", digits)
            pexpr = not isinstance(v, int) and not wide              # a PARAMETER expression as the value
            if _isint(w) and pexpr:
                return f"{w}'({wtxt(v)})"                            # k(sub(ticks,1), 10) -> 10'(TICKS-1), not 10'dticks
            digits = v[1] if wide else str(v)
            if _isint(w):
                return f"{w}'d{digits}"
            if wide or (isinstance(v, int) and v >= 2 ** 31):
                raise PrintError(f"a wide constant at a parametric width ({term_to_str(t)}) is not printable")
            if isinstance(w, str) and (isinstance(v, int) or pexpr):
                # a constant OR a parameter expression at a named parametric width: the SV
                # size-cast, inline -- `COUNTWIDTH'(DEPTH-DEMANDRESERVE)`. Without the pexpr
                # half, a parameterized threshold fell back to a hoisted wire (and before
                # that, the generator baked the number -- the user's review, 2026-08-31)
                return f"{w.upper()}'({v if isinstance(v, int) else wtxt(v)})"
            return self.wire(w, wtxt(v) if not isinstance(v, int) else digits)   # sized by the wire's declaration
        if t[0] == "tag":
            return t[1]
        w = width_of(self.d, t)
        return self.wire(w, self.expr(t))

    def widened(self, t, w: int) -> str:
        """`t` as a leaf of EXACTLY width w (zero-extended through a wire when narrower) -- for the
        ops whose @func reads the sign bit at the op width."""
        tw = width_of(self.d, t)
        if isinstance(tw, tuple):
            raise PrintError(f"enum operand under an arithmetic op: {term_to_str(t)}")
        leaf = self.leaf(t)
        if tw == w:                        # ints, or the same parameter expression
            return leaf
        return self.wire(w, leaf)          # assign zero-extends

    def expr(self, t) -> str:
        """`t` as ONE SV operator applied to leaves (operands hoisted as needed)."""
        if isinstance(t, str) or t[0] in ("k", "tag"):
            return self.leaf(t)
        op = t[0]
        if op in BIN_OPS:
            return f"{self.leaf(t[1])} {BIN_OPS[op]} {self.leaf(t[2])}"
        if op == "ashr":
            w = t[3]
            return f"$signed({self.widened(t[1], w)}) >>> {self.leaf(t[2])}"
        if op in ("sidiv", "simod"):
            w = t[3]
            return f"$signed({self.widened(t[1], w)}) {'/' if op == 'sidiv' else '%'} $signed({self.widened(t[2], w)})"
        if op in ("slt", "sle", "sgt", "sge"):
            w = t[3]
            o = {"slt": "<", "sle": "<=", "sgt": ">", "sge": ">="}[op]
            return f"$signed({self.widened(t[1], w)}) {o} $signed({self.widened(t[2], w)})"
        if op == "bnot":
            return f"~{self.widened(t[1], t[2])}"
        if op == "neg":
            return f"-{self.widened(t[1], t[2])}"
        if op == "sext":
            f, w = t[2], t[3]
            a = self.widened(t[1], f)
            if w == f:
                return a
            if _isint(w) and _isint(f):
                return f"{{{{{w - f}{{{a}[{f - 1}]}}}}, {a}}}"
            return f"{{{{({wtxt(w)}-{wtxt(f)}){{{a}[{wtxt(f)}-1]}}}}, {a}}}"
        if op == "slc":
            lo, w = t[2], t[3]
            a = self.leaf(t[1])
            if _isint(lo) and _isint(w):
                return f"{a}[{lo + w - 1}:{lo}]" if w > 1 else f"{a}[{lo}]"
            return f"{a}[{wtxt(lo)}+{wtxt(w)}-1:{wtxt(lo)}]"
        if op == "bit":
            return f"{self.leaf(t[1])}[{wtxt(t[2])}]"
        if op == "cat":
            return f"{{{self.leaf(t[1])}, {self.leaf(t[3])}}}"
        if op == "mrd":                      # a flop-array read is an index, not a port
            return f"{t[1]}[{self.leaf(t[2])}]"
        if op == "pack":
            # A LANE IS ALREADY A PACKED VECTOR HERE (`logic [N-1:0] cap`), so its packed word is
            # simply its name -- `assign out_byte = cap;`. One line, and parametric because
            # nothing about it mentions the extent. The alternative the language forced before
            # this existed was a hand-written weighted sum, whose per-element weights made the
            # printed module lie about honouring its parameter (G20).
            return _sv_ident(t[1])
        if op == "lnot":
            return f"~{self.leaf(t[1])}"      # bitwise at 1 bit, same reason as BIN_OPS' & and |
        red = {"ror": "|", "rand": "&", "rxor": "^", "rnand": "~&", "rnor": "~|", "rxnor": "~^",
               "parity": "^"}
        if op in red:
            return f"{red[op]}{self.leaf(t[1])}"
        if op == "popcnt":
            return f"$countones({self.leaf(t[1])})"
        if op == "clz":
            raise PrintError(
                "clz has no print form yet. It is wired for AUTHORING and LINTING only, because there is no SystemVerilog construct for a leading-zero count -- lowering one means synthesising a priority encoder, a design decision nothing has needed yet. Until then a design that needs an LZC declares it as a CONTRACT-ONLY submodule and is proven from its contract; the print gives it as an interface stub. See notes/WORKLIST_SPEC2RTL.md.")
        if op == "ite":
            return f"{self.leaf(t[1])} ? {self.leaf(t[2])} : {self.leaf(t[3])}"
        raise PrintError(f"unknown operator {op}")


