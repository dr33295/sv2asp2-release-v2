def print_sv(d: Design, mode: str = "behav", src: str = "<design>.lp",
             certified: "set | None" = None) -> str:
    """The SystemVerilog text. `certified` = the guarded heads proven total (bare `else` allowed);
    None = compute the certificate for every guarded head now."""
    if mode not in ("cells", "behav"):
        raise PrintError(f"mode is cells or behav, not {mode!r}")
    if d.abstract_nets():
        raise PrintError(f"{len(d.abstract_nets())} net(s) still abstract -- not printable until every "
                         f"one is refined: {', '.join(d.abstract_nets())}")
    # (an abstract MODULE INSTANCE is printable: the parent instantiates it and print_hier emits an
    #  interface STUB for the module -- the RTL of this level alone, its children as black boxes)
    if certified is None:
        certified = {h for h in d.rule_heads() if totality_certificate(d, h)}
    for p in d.ports:
        if isinstance(p.width, tuple):
            raise PrintError(f"enum-typed port {p.name}: not printable yet (M5); use a logic port + a def")
    out: list = [HEADER.format(src=pathlib.Path(src).name)]
    # typedefs before the module (SV needs a type visible to the port list; internal only here)
    for e, ms in d.enums.items():
        w = enum_width(ms)
        body = ", ".join(f"{l} = {v}" for l, v in ms)
        out.append(f"typedef enum logic [{w - 1}:0] {{ {body} }} {enum_tname(e)};")
    if d.enums:
        out.append("")
    # header -- with the module's PARAMETERS when it has any (numeric params overridable, expression
    # params as localparams inside), every width printed symbolically from the raw (unresolved) design
    raw = d.raw
    pw = (lambda p: raw.port_w.get(p.name, p.width)) if raw is not None else (lambda p: p.width)
    nw = (lambda n: raw.net_w.get(n.name, n.width)) if raw is not None else (lambda n: n.width)
    is_member = lambda name: _lane_member(d, name) is not None
    # a lane's COUNT prints as written -- a parameter stays a parameter (`d [N]`, `i < N`), a number a number
    ln_n = (lambda name, N: wtxt(raw.lane_n.get(name, N))) if raw is not None else (lambda name, N: str(N))
    ln_w = (lambda name, W: raw.lane_w.get(name, W)) if raw is not None else (lambda name, W: W)

    def ln_n_axes(ln, N):
        """The extent text per axis (a tuple) for a lane with more than one axis, else ln_n(ln, N)."""
        ax = axes_of(d.lanes, ln)
        if len(ax) == 1:
            return ln_n(ln, N)
        raw_ax = raw.lane_axes.get(ln) if raw is not None else None
        return tuple(wtxt(raw_ax[k]) if raw_ax is not None else str(ax[k]) for k in range(len(ax)))
    ports = [f"  {p.direction} {_wdecl(pw(p))} {p.name}" for p in d.ports if not is_member(p.name)]
    for ln, (N, W, dr) in d.lanes.items():
        if dr:
            ports.append(f"  {dr} {_lane_decl(ln_n_axes(ln, N), ln_w(ln, W))} {ln}")
    numeric, hdr_derived, body_derived = _split_params(d, raw)
    if numeric or hdr_derived:
        out.append(f"module {d.name} #(")
        out.append(",\n".join([f"  parameter {k.upper()} = {v}" for k, v in numeric]
                              + [f"  localparam {k.upper()} = {wtxt(v)}" for k, v in hdr_derived]))
        out.append(") (")
    else:
        out.append(f"module {d.name} (")
    out.append(",\n".join(ports))
    out.append(");")
    for k, v in body_derived:
        out.append(f"  localparam {k.upper()} = {wtxt(v)};")
    # nets (a lane is ONE unpacked-array declaration; its members are not repeated)
    for n in d.nets:
        if not is_member(n.name):
            out.append(f"  {_wdecl(nw(n))} {n.name};")
    for ln, (N, W, dr) in d.lanes.items():
        if not dr:
            out.append(f"  {_lane_decl(ln_n_axes(ln, N), ln_w(ln, W))} {ln};")
    # a FLOP ARRAY is declared here, with the other declarations, not beside its always_ff: its
    # readers are `mrd(M, A)` expressions printed at their USE sites, which come first, and
    # SystemVerilog requires an array to be declared before it is read (Icarus: "Unable to bind
    # wire/reg/memory `tab[ra]' ... Check for declaration after use")
    for i in d.insts:
        if i.cell == "farray":
            # RAW iparams, exactly as _inst_sv's ip() reads them: this declaration printed from
            # the RESOLVED values once, so a parametric module's storage came out as fixed
            # numbers -- parameters that were real everywhere else and fake here (the user's
            # catch on the v2 FIFO: `logic [7:0] storage [0:3]` under `#(parameter DEPTH,
            # WIDTH)` -- an override would have silently built wrong hardware).
            gp = (lambda k: d.raw.iparams.get((i.name, k), i.iparams.get(k))) if d.raw is not None \
                else (lambda k: i.iparams.get(k))
            fw, fdep = gp("width"), gp("depth")
            fhi = f"{fw - 1}" if _isint(fw) else f"{wtxt(fw)}-1"
            ftop = f"{fdep - 1}" if _isint(fdep) else f"{wtxt(fdep)}-1"
            out.append(f"  logic [{fhi}:0] {i.name} [0:{ftop}];")
    out.append("")
    # combinational defs (a lane member inside a lane def's WINDOW is printed by that generate below; a
    # member outside every window -- the boundary lane of a chain, `def(y(0), ...)` -- is a plain assign)
    import itertools as _it
    covered = set()
    for ln, iv, _e, lo, hi in d.lane_defs:            # the members a generate block prints
        if isinstance(iv, tuple):
            covered |= {member(ln, *idx) for idx in _it.product(*(range(a, b + 1) for a, b in zip(lo, hi)))}
        else:
            covered |= {f"{ln}({i})" for i in range(lo, hi + 1)}
    for n in d.def_order:
        if n in covered:
            continue
        ctx = _Ctx(d, n)
        term = raw.defs[n] if raw is not None and n in raw.defs else d.defs[n]
        rhs = ctx.expr(term)
        out.extend(ctx.decls)
        out.extend(ctx.assigns)
        lm = _lane_member(d, raw.def_targets.get(n, n) if raw is not None else n)
        w = width_of(d, n)
        if isinstance(w, tuple) and w and w[0] == "enum" and isinstance(term, tuple) and term[0] == "ite":
            rhs = f"{enum_tname(w[1])}'({rhs})"   # an enum-typed ternary needs an explicit cast (Icarus: "requires an explicit cast")
        out.append(f"  assign {_sv_ref(lm) if lm else n} = {rhs};")
    # lane defs: one generate block per lane, the def once with the index as the genvar, the bounds from the
    # WINDOW (`x(I-1)` in the body starts it at 1; `x(I+1)` ends it at N-2 -- printed `i < N-1` when N is a param)
    # RELATED LANES SHARE ONE GENERATE BLOCK (the regeneration run's grouping
    # requirement): consecutive lane defs with the same index range -- a slot's CAM
    # nets, a run of chains, the M1 next-value cluster -- print inside one block,
    # labelled by their first member, instead of one block per net.
    runs, cur = [], None
    for ln, ivs, e, los, his in [x for x in d.lane_defs if isinstance(x[1], tuple)]:
        # a MULTI-AXIS lane def: one nested generate per def, the window per axis (2026-09-03)
        ax = axes_of(d.lanes, ln)
        ax_txt = ln_n_axes(ln, d.lanes[ln][0])
        heads = []
        for k, (iv, lo, hi) in enumerate(zip(ivs, los, his)):
            n_txt = ax_txt[k]
            cut = ax[k] - 1 - hi
            hi_txt = str(hi + 1) if n_txt.isdigit() else (f"{n_txt}-{cut}" if cut else n_txt)
            heads.append(f"for (genvar {iv.lower()} = {lo}; {iv.lower()} < {hi_txt}; {iv.lower()}++)")
        ctx = _Ctx(d, ln, axes_txt=tuple(ax_txt), gv=tuple(iv.lower() for iv in ivs))
        rhs = ctx.expr(raw.lane_defs.get(ln, e) if raw is not None else e)
        out.extend(ctx.decls)                                # module-level lanes, before the block
        out.append(f"  generate {' '.join(heads)} begin : g_{ln}")
        out.extend(ctx.assigns)
        out.append(f"    assign {ln}{''.join(f'[{iv.lower()}]' for iv in ivs)} = {rhs};")
        out.append("  end endgenerate")
    for ln, iv, e, lo, hi in d.lane_defs:
        if isinstance(iv, tuple):
            continue
        N = d.lanes[ln][0]
        i = iv.lower()
        cut = N - 1 - hi
        n_txt = ln_n(ln, N)
        hi_txt = str(hi + 1) if n_txt.isdigit() else (f"{n_txt}-{cut}" if cut else n_txt)
        key = (i, lo, hi_txt)
        if cur is None or cur[0] != key:
            cur = (key, [])
            runs.append(cur)
        cur[1].append((ln, e))
    for (i, lo, hi_txt), members in runs:
        out.append(f"  generate for (genvar {i} = {lo}; {i} < {hi_txt}; {i}++) "
                   f"begin : g_{members[0][0]}")
        for ln, e in members:
            ctx = _Ctx(d, ln)
            rhs = ctx.expr(raw.lane_defs.get(ln, e) if raw is not None else e)
            out.extend("  " + x for x in ctx.decls)
            out.extend("  " + x for x in ctx.assigns)
            out.append(f"    assign {ln}[{i}] = {rhs};")
        out.append("  end endgenerate")
    # guarded rules
    for h in d.rule_heads():
        rules = [r for r in d.rules if r.head == h]
        ctx = _Ctx(d, h)
        arms = [(_rule_cond(ctx, d, r), _value_text(ctx, d, h, _rule_value_term(r))) for r in rules]
        out.extend(ctx.decls)
        out.extend(ctx.assigns)
        out.append("  always_comb begin")
        for i, (c, v) in enumerate(arms):
            last = i == len(arms) - 1
            if i == 0:
                out.append(f"    if ({c}) {h} = {v};")
            elif last and h in certified:
                out.append(f"    else {h} = {v};   // total: proven by the totality certificate")
            else:
                out.append(f"    else if ({c}) {h} = {v};")
        if h not in certified:
            out.append(f"    // no totality certificate for {h}: no default arm on purpose -- an "
                       f"uncovered case is a translation-time PROBLEM, not a latch")
        out.append("  end")
    # state (lane instances: one generate block, the cell once with the index as the genvar)
    is_lane_inst = lambda name: (parse_ref(name) is not None and parse_ref(name).base in d.lane_insts)
    for i in d.insts:
        if is_lane_inst(i.name):
            continue
        out.append("")
        out.extend(_inst_sv(d, i, mode))
    # the slot FLOPS share one generate block per count, for the same grouping reason
    inst_runs, cur = [], None
    for u, (cell, N) in d.lane_insts.items():
        if u in getattr(d, "inst_axes", {}):
            # a MULTI-AXIS instance lane: one nested generate, the cell once, each lane pin the
            # member at the same position (2026-09-03)
            ax = d.inst_axes[u]
            raw_ax = raw.lane_axes.get(u) if raw is not None else None
            gv = ["i", "j", "k", "l"][:len(ax)]
            heads = []
            for k_, ext in enumerate(ax):
                n_txt = wtxt(raw_ax[k_]) if raw_ax is not None else str(ext)
                heads.append(f"for (genvar {gv[k_]} = 0; {gv[k_]} < {n_txt}; {gv[k_]}++)")
            out.append("")
            out.append(f"  generate {' '.join(heads)} begin : g_{u}")
            first = next(x for x in d.insts if x.name == member(u, *([0] * len(ax))))
            pins = {}
            for pn, net in first.pins.items():
                lm = _lane_member(d, net)
                pins[pn] = f"{lm[0]}{''.join(f'[{g}]' for g in gv)}" if lm is not None else net
            rolled = type(first)(u, cell, pins, dict(first.iparams), dict(first.mparams))
            out.extend("  " + x for x in _inst_sv(d, rolled, mode))
            out.append("  end endgenerate")
            continue
        key = ln_n(u, N)
        if cur is None or cur[0] != key:
            cur = (key, [])
            inst_runs.append(cur)
        cur[1].append((u, cell, N))
    for n_txt, members in inst_runs:
        out.append("")
        out.append(f"  generate for (genvar i = 0; i < {n_txt}; i++) "
                   f"begin : g_{members[0][0]}")
        for u, cell, N in members:
            first = next(x for x in d.insts if x.name == f"{u}(0)")
            pins = {}
            for pn, net in first.pins.items():
                lm = _lane_member(d, net)
                pins[pn] = f"{lm[0]}[i]" if lm is not None else net
            rolled = type(first)(u, cell, pins, dict(first.iparams), dict(first.mparams))
            out.extend("  " + x for x in _inst_sv(d, rolled, mode))
        out.append("  end endgenerate")
    out.append("endmodule")
    return "\n".join(out) + "\n"


def _inst_sv(d: Design, i, mode: str) -> list:
    # a scalar instance's pin on a lane MEMBER (`pin(u, d, q(3))`) prints as `q[3]`
    p = {k: (_sv_ref(_lane_member(d, v)) if _lane_member(d, v) else v) for k, v in i.pins.items()}
    ip = (lambda k: d.raw.iparams.get((i.name, k), i.iparams[k])) if d.raw is not None else (lambda k: i.iparams[k])
    if i.cell not in ("ff", "arff", "lata", "spram", "farray"):
        # an AUTHORED module: a plain instantiation (with its parameter overrides); the module itself is
        # printed separately (print_hier)
        conns = ", ".join(f".{port}({net})" for port, net in p.items())
        ov = (" #(" + ", ".join(f".{k.upper()}({v})" for k, v in i.mparams.items()) + ")") if i.mparams else ""
        return [f"  {i.cell}{ov} {i.name} ({conns});"]
    if i.cell == "spram":
        w, depth = ip("width"), ip("depth")
        if not (_isint(w) and _isint(depth)):
            return [f"  logic [{wtxt(w)}-1:0] {i.name} [0:{wtxt(depth)}-1];",
                    f"  always_ff @(posedge {p['clk']}) if ({p['we']}) {i.name}[{p['wa']}] <= {p['wd']};",
                    f"  assign {p['rd']} = {i.name}[{p['ra']}];"]
        return [f"  logic [{w - 1}:0] {i.name} [0:{depth - 1}];",
                f"  always_ff @(posedge {p['clk']}) if ({p['we']}) {i.name}[{p['wa']}] <= {p['wd']};",
                f"  assign {p['rd']} = {i.name}[{p['ra']}];"]
    if i.cell == "farray":
        # an array of REGISTERS: the write port, and an async reset that clears EVERY cell (the shape
        # an SRAM cannot have). Its readers are `mrd(M, A)` expressions printed at their use sites.
        w, depth = ip("width"), ip("depth")
        hi = f"{w - 1}" if _isint(w) else f"{wtxt(w)}-1"
        top = f"{depth - 1}" if _isint(depth) else f"{wtxt(depth)}-1"
        _ = (hi, top)                       # the DECLARATION is emitted with the other nets, above
        rst = p.get("rstL")
        if rst is None:
            return [f"  always_ff @(posedge {p['clk']}) if ({p['we']}) {i.name}[{p['wa']}] <= {p['wd']};"]
        rv = ip("reset_value")
        return [f"  always_ff @(posedge {p['clk']} or negedge {rst})",
                f"    if (!{rst}) for (int unsigned gi = 0; gi <= {top}; gi++) {i.name}[gi] <= {wtxt(rv)};",
                f"    else if ({p['we']}) {i.name}[{p['wa']}] <= {p['wd']};"]
    if i.cell == "lata":
        # the classic inferred-latch idiom: transparent while en is high, holds otherwise --
        # the shape sv2asp's allow_latches path and Icarus both handle (latch_demo's family).
        # The round trip's generated manifest sets allow_latches when a design carries one.
        return [f"  always @* if ({p['en']}) {p['q']} = {p['d']};"]
    q_w = d.width_of(i.pins["q"])
    enum_reg = isinstance(q_w, tuple)
    if i.cell == "ff":
        if mode == "cells" and not enum_reg:
            return [f"  FF #(.WIDTH({wtxt(ip('width'))})) {i.name} "
                    f"(.clk({p['clk']}), .en({p['en']}), .d({p['d']}), .q({p['q']}));"]
        if d.defs.get(p['en']) == ("k", 1, 1):
            return [f"  always_ff @(posedge {p['clk']})",
                    f"    {p['q']} <= {p['d']};"]
        return [f"  always_ff @(posedge {p['clk']})",
                f"    if ({p['en']}) {p['q']} <= {p['d']};"]
    if i.cell == "arff":
        rv = i.iparams["reset_value"]
        w = ip("width")
        if mode == "cells" and not enum_reg:
            return [f"  ARFF #(.WIDTH({wtxt(w)}), .RESET_VALUE({rv})) {i.name} "
                    f"(.clk({p['clk']}), .en({p['en']}), .rstL({p['rstL']}), .d({p['d']}), .q({p['q']}));"]
        if enum_reg:
            # AN ENUM REGISTER RESETS TO A MEMBER, not to its number: SystemVerilog enums are
            # strongly typed, and `st <= 2'd0` into `st_t st` is "requires an explicit cast"
            # (iverilog). The value the author wrote is looked up among the members; a value
            # no member carries is refused by name, because a reset to a non-member is an
            # authoring error the type exists to catch (G21, 2026-09-02).
            members = d.enums.get(q_w[1], [])
            hit = [l for l, v in members if v == rv]
            if isinstance(rv, str) and any(l == rv for l, _ in members):
                rv_t = rv                                   # already a member name
            elif hit:
                rv_t = hit[0]
            else:
                raise PrintError(f"{i.name}: reset_value {rv!r} is not a member of enum "
                                 f"{q_w[1]} ({', '.join(l for l, _ in members)})")
        elif _isint(w):
            rv_t = f"{w}'d{rv}"
        else:
            rv_t = "'0" if rv == 0 else f"{wtxt(w)}'({rv})"          # a parametric width: SV fill / size cast
        en = p['en']
        always_on = d.defs.get(en) == ("k", 1, 1)
        tail = (f"    else {p['q']} <= {p['d']};" if always_on
                else f"    else if ({en}) {p['q']} <= {p['d']};")
        return [f"  always_ff @(posedge {p['clk']} or negedge {p['rstL']})",
                f"    if (!{p['rstL']}) {p['q']} <= {rv_t};",
                tail]
    raise PrintError(f"{i.name}: unknown cell {i.cell}")


