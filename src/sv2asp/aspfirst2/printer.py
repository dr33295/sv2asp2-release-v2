def enum_tname(net: str) -> str:
    """The SystemVerilog TYPE name for the enum whose members `enum_member(net, ...)` declare.

    `d.enums` is keyed by the NET, and the printer used that key as the typedef name -- so
    `typedef enum ... st;` collided with `logic [1:0] st;` and iverilog refused the file at
    the declaration. Everything else about named states already worked (an enum-typed
    intermediate prints as `st stM1;`, its ternary as `st'(d ? one : none)`, a compare as
    `st == two`); one block fell back to numeric encodings in its RTL for want of this
    suffix (G21, 2026-09-02). The ASP-side spelling `enum(st)` is unchanged.
    """
    return f"{net}_t"


def enum_width(members: list) -> int:
    mx = max(v for _, v in members)
    return max(1, mx.bit_length())


def width_of(d: Design, t) -> object:
    """Result width of a term: an int, or ("enum", E) for a tag / enum net."""
    if isinstance(t, str):
        lm = _lane_member(d, t)
        if lm is not None:
            return d.raw.lane_w.get(lm[0], d.lanes[lm[0]][1]) if d.raw is not None else d.lanes[lm[0]][1]
        if d.raw is not None and (t in d.raw.net_w or t in d.raw.port_w):
            return d.raw.net_w.get(t, d.raw.port_w.get(t))
        w = d.width_of(t)
        if w is None:
            raise PrintError(f"undeclared net {t}")
        return w
    op = t[0]
    if op == "k":
        return t[2]
    if op == "tag":
        for e, ms in d.enums.items():
            if any(l == t[1] for l, _ in ms):
                return ("enum", e)
        raise PrintError(f"unknown tag {t[1]}")
    if op in ("add", "sub", "mul", "and", "or", "xor", "shl", "shr", "ashr", "idiv", "imod",
              "sidiv", "simod", "sext", "slc"):
        return t[-1]
    if op in ("bnot", "neg"):
        return t[2]
    if op == "bit":
        return 1
    if op == "cat":
        return t[2] + t[4] if _isint(t[2]) and _isint(t[4]) else ("add", t[2], t[4])
    if op == "pack":                         # the whole lane: every member side by side
        n, w, _dir = d.lanes[t[1]]
        return n * w if isinstance(n, int) and isinstance(w, int) else ("mul", n, w)
    if op == "mrd":                          # a flop-array read is one CELL: the array's width
        for i in d.insts:
            if i.name == t[1]:
                return i.iparams.get("width")
        for m, (_dep, w) in getattr(d, "arch_mems", {}).items():
            if m == t[1]:
                return w
        raise PrintError(f"mrd of an undeclared array {t[1]}")
    if op in ("eq", "ne", "lt", "le", "gt", "ge", "slt", "sle", "sgt", "sge", "logand", "logor",
              "lnot", "ror", "rand", "rxor", "rnand", "rnor", "rxnor", "parity"):
        return 1
    if op == "popcnt":
        return t[2]
    if op == "clz":
        raise PrintError(
            "clz has no print form yet. It is wired for AUTHORING and LINTING only, because there is no SystemVerilog construct for a leading-zero count -- lowering one means synthesising a priority encoder, a design decision nothing has needed yet. Until then a design that needs an LZC declares it as a CONTRACT-ONLY submodule and is proven from its contract; the print gives it as an interface stub. See notes/WORKLIST_SPEC2RTL.md.")
    if op == "ite":
        return width_of(d, t[2])
    raise PrintError(f"unknown operator {op}")


def _isint(w) -> bool:
    return isinstance(w, int)




def _param_names(t, acc: set) -> set:
    """Every parameter NAME a parameter expression mentions (the operator head is not a name)."""
    if isinstance(t, str):
        acc.add(t)
    elif isinstance(t, tuple):
        for a in t[1:]:
            _param_names(a, acc)
    return acc


def _split_params(d, raw):
    """(header, body) derived parameters.

    A derived parameter goes in the PARAMETER PORT LIST only when a PORT declaration references it:
    there, a body `localparam` would be a declaration after use and will not elaborate
    (`output logic [CW-1:0] lz` with `localparam CW` below the port list). Everything else stays in
    the body, so a module whose ports need none prints exactly as it did before this rule existed.
    Closed transitively -- a needed derived parameter may be defined in terms of another."""
    numeric = [(k, v) for k, v in d.param_exprs.items() if isinstance(v, int)] if raw is not None else []
    derived = [(k, v) for k, v in d.param_exprs.items() if not isinstance(v, int)] if raw is not None else []
    if not derived:
        return numeric, [], []
    refs: set = set()
    for prt in d.ports:
        _param_names(raw.port_w.get(prt.name, prt.width), refs)
    for ln, (N, W, dr) in d.lanes.items():
        if dr:
            _param_names(raw.lane_n.get(ln, N), refs)
            _param_names(raw.lane_w.get(ln, W), refs)
    dmap = dict(derived)
    need: set = set()
    stack = [x for x in refs if x in dmap]
    while stack:
        k = stack.pop()
        if k in need:
            continue
        need.add(k)
        stack.extend(x for x in _param_names(dmap[k], set()) if x in dmap)
    return numeric, [kv for kv in derived if kv[0] in need], [kv for kv in derived if kv[0] not in need]


def _lane_member(d: Design, name: str):
    """(base, index) if `name` is a lane member `x(3)` / a rolled ref `x(I)`, `x(I-1)` /
    a WRAPPING ref `x(I-16 \\ 256)`, else None. A wrap's index is pre-rendered to the SV
    expression of its load-time meaning, (I//B)*B + ((I%B)+k) mod B -- with the offset
    normalised non-negative so SV's % (remainder, like clingo's \\) agrees with the wrap --
    and simplified to a plain ring (I+k)%B when B is the lane's whole extent. Without this
    the toroid's neighbour refs printed as raw ASP terms inside the generate body (found by
    ve144_conwaylife's round trip: `assign up[i] = q(I-16 \\ 256);`).
    """
    r = parse_ref(name)
    if not (r and r.base in d.lanes):
        return None
    axes = axes_of(d.lanes, r.base)
    if len(r.idx) != len(axes):
        return None
    if len(axes) > 1:
        # a MULTI-AXIS member / rolled reference: each axis rendered as the 1-D rule renders
        # its one axis, joined as `x[r][c]` (2026-09-03)
        raw_axes = d.raw.lane_axes.get(r.base) if d.raw is not None else None
        parts = []
        for k, ix in enumerate(r.idx):
            ext = axes[k]
            ext_txt = (str(raw_axes[k]).upper() if raw_axes is not None and not isinstance(raw_axes[k], int) else str(ext))
            parts.append(_axis_sv(d, ix, ext, ext_txt))
        return r.base, "][".join(parts)
    base, ix = r.base, r.idx[0]
    mod = ix.mod
    if ix.is_const:
        return base, str(ix.const)
    if mod is None and not ix.off:
        # A genvar prints lowercase (`x[i]`); a module PARAMETER prints uppercase, matching the
        # localparam the print declares (`x[TOP]`); a literal is left alone.
        return base, ix.var.upper() if ix.var in d.params else ix.var.lower()
    if mod is None:
        return base, f"{ix.var.lower()}{ix.off}"        # `x[i-1]` -- the offset is a number here
    var = ix.var.lower()
    # a NUMBER prints as itself; a PARAMETER prints as the localparam the module declares, so
    # the generate body is parametric where the offsets are -- `q[((i + (CELLS - SIDE)) % CELLS)]`
    # rather than a 240 baked at one size (G28, 2026-09-02)
    B = int(mod) if mod.isdigit() else d.params[mod]
    btxt = mod if mod.isdigit() else mod.upper()
    ot = ix.off or "+0"
    sign, off = ot[0], ot[1:]
    if off.isdigit() and mod.isdigit():
        kp = (int(off) if sign == "+" else -int(off)) % B    # Python % is non-negative
        ktxt = str(kp)
    elif off.isdigit():
        # a literal offset against a PARAMETER block: the residue depends on the parameter's
        # value, so `-1` prints as `(SIDE - 1)`, never as the 2 it happens to be at SIDE = 3
        ktxt = off if sign == "+" else f"({btxt} - {off})"
    else:
        name = off.upper()
        ktxt = name if sign == "+" else f"({btxt} - {name})"    # a non-negative residue, symbolically
    extent = d.lanes[base][0]
    if B == extent:
        return base, f"(({var} + {ktxt}) % {btxt})"
    return base, f"(({var}/{btxt})*{btxt} + (({var}%{btxt} + {ktxt}) % {btxt}))"


def _axis_sv(d: Design, ix, extent: int, ext_txt: str) -> str:
    """One axis of a multi-axis lane reference as SV: a number; a genvar; `(r + k) % B` for a
    wrap over the whole axis (a ring), the block form otherwise; parameters by their localparam
    names, a literal offset against a parameter block kept symbolic (`(SIDE - 1)`)."""
    if ix.is_const:
        return str(ix.const)
    var = ix.var.lower()
    if ix.mod is None:
        return var + ix.off if ix.off else var
    mod = ix.mod
    B = int(mod) if mod.isdigit() else d.params[mod]
    btxt = mod if mod.isdigit() else mod.upper()
    ot = ix.off or "+0"
    sign, off = ot[0], ot[1:]
    if off.isdigit() and mod.isdigit():
        ktxt = str((int(off) if sign == "+" else -int(off)) % B)
    elif off.isdigit():
        ktxt = off if sign == "+" else f"({btxt} - {off})"
    else:
        name = off.upper()
        ktxt = name if sign == "+" else f"({btxt} - {name})"
    if B == extent:
        return f"(({var} + {ktxt}) % {btxt})"
    return f"(({var}/{btxt})*{btxt} + (({var}%{btxt} + {ktxt}) % {btxt}))"


def _sv_ref(lm) -> str:
    """`x[3]` / `x[i]` / `x[i-1]` / `x[TOP]` / `x[((i + 240) % 256)]` for a lane member.
    The index arrives already rendered by `_lane_member`, which knows the design's parameters."""
    return f"{lm[0]}[{lm[1]}]"


def _sv_ident(name: str) -> str:
    """A hoisting-safe identifier for a lane member: `y(0)` -> `y_0`."""
    return re.sub(r"[()+-]", "_", name).rstrip("_")


def wtxt(w) -> str:
    """A width as SV text: a number, a PARAMETER (upper-cased), or an expression over parameters."""
    if isinstance(w, int):
        return str(w)
    if isinstance(w, str):
        return w.lower() if is_var(w) else w.upper()      # a lane's loop variable is a genvar; a parameter a localparam
    if isinstance(w, tuple):
        if w[0] == "log2":
            return f"$clog2({wtxt(w[1])})"
        if w[0] in ("add", "sub", "mul") and len(w) == 3:
            return f"({wtxt(w[1])}{ {'add': '+', 'sub': '-', 'mul': '*'}[w[0]] }{wtxt(w[2])})"
    raise PrintError(f"not a width: {w!r}")


def _wdecl(w) -> str:
    """The SV type of a width."""
    if isinstance(w, tuple) and w and w[0] == "enum":
        return enum_tname(w[1])            # the enum typedef name, distinct from the net's
    if _isint(w):
        return "logic" if w == 1 else f"logic [{w - 1}:0]"
    return f"logic [{wtxt(w)}-1:0]"        # a parametric width


def _lane_decl(n_txt: str, w) -> str:
    """The SV type of a LANE (N members of width W) -- PACKED: `logic [N-1:0]` for 1-bit lanes (a
    vector: `req[i]`), `logic [N-1:0][W-1:0]` for wider ones (a packed 2-D: `q[i]` is an 8-bit
    element). Packed rather than an unpacked array (`logic [W-1:0] q [N]`) because that is the
    translator's LANE model (`val(q(I), V, T)` with the word<->lane bridge) -- the unpacked form is
    its MEMORY model (`addr`/cells), the shape `spram` prints to -- and because a lane read as a
    whole word (`{q[3], q[2], ..}`) is then free."""
    if isinstance(w, tuple) and w and w[0] == "enum":
        raise PrintError("an enum lane is not printable")
    dims = n_txt if isinstance(n_txt, tuple) else (n_txt,)
    n_dim = "".join(f"[{a}-1:0]" if not a.isdigit() else f"[{int(a) - 1}:0]" for a in dims)
    if _isint(w) and w == 1:
        return f"logic {n_dim}"
    return f"logic {n_dim}{_wdecl(w)[len('logic '):]}"


