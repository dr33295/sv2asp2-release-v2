def _rule_value_term(r: Rule):
    """The rule's head value as an expression term over the READ signals (steps folded in)."""
    env: dict = {}
    for s, v in r.reads:
        env[v] = s
    fmap = {"add": "add", "sub": "sub", "mul": "mul", "idiv": "idiv", "imod": "imod",
            "sidiv": "sidiv", "simod": "simod", "band": "and", "bor": "or", "bxor": "xor",
            "shl": "shl", "shr": "shr", "ashr": "ashr", "bnot": "bnot", "neg": "neg",
            "sext": "sext", "slc": "slc", "parity": "parity", "popcnt": "popcnt",
            "rand": "rand", "ror": "ror", "rxor": "rxor", "rnand": "rnand", "rnor": "rnor",
            "rxnor": "rxnor"}
    for st in r.steps:
        if st.func not in fmap:
            raise PrintError(f"@{st.func} in a comb rule is not printable (line {r.line})")
        op = fmap[st.func]
        args = []
        nval = {"add": 2, "sub": 2, "mul": 2, "idiv": 2, "imod": 2, "sidiv": 2, "simod": 2,
                "band": 2, "bor": 2, "bxor": 2, "shl": 2, "shr": 2, "ashr": 2, "bnot": 1,
                "neg": 1, "sext": 1, "slc": 1, "parity": 1, "popcnt": 1, "rand": 1, "ror": 1,
                "rxor": 1, "rnand": 1, "rnor": 1, "rxnor": 1}[st.func]
        wargs = st.args[nval:]
        w = wargs[-1] if wargs else None
        for a in st.args[:nval]:
            if isinstance(a, str):
                if a not in env:
                    raise PrintError(f"unbound {a} in step (line {r.line})")
                args.append(env[a])
            else:                                       # a constant operand: needs the op width
                if not isinstance(w, int):
                    raise PrintError(f"constant operand without a width in @{st.func} (line {r.line})")
                args.append(("k", a, w))
        env[st.var] = (op, *args, *wargs)
    v = r.value
    if isinstance(v, tuple) and v[0] == "var":
        return env[v[1]]
    return v                                            # int or tag label


def _rule_cond(ctx: "_Ctx", d: Design, r: Rule) -> str:
    """The arm's condition. A compare on an ENUM signal (a tag compare) is hoisted into its own
    1-bit wire: the translator lowers `state == idle` as a tag guard only when it stands alone
    (inside `&&` it would be handed to the @func cascade as a symbol and is refused, loudly)."""
    conds = []
    var_sig = {v: s for s, v in r.reads}
    lits = [(s, "==", c) for s, c in r.guards] + \
           [(var_sig[v], op if op != "=" else "==", c) for v, op, c in r.cmps]
    for s, op, c in lits:
        text = f"{s} {op} {_const_text(d, s, c)}"
        if isinstance(d.width_of(s), tuple):
            text = ctx.wire(1, text)
        conds.append(text)
    return " && ".join(f"({c})" if " " in c else c for c in conds) if len(conds) > 1 else conds[0]


def _const_text(d: Design, sig: str, c) -> str:
    w = d.width_of(sig)
    if isinstance(w, tuple):
        return str(c)                                    # a tag
    if isinstance(c, tuple):                             # ("str", digits)
        return f"{w}'d{c[1]}"
    return f"{w}'d{c}"


def _value_text(ctx: _Ctx, d: Design, head: str, v) -> str:
    w = d.width_of(head)
    if isinstance(v, int):
        return f"{w}'d{v}" if not isinstance(w, tuple) else str(v)
    if isinstance(v, str):
        return v                                         # a tag label
    return ctx.leaf(v)


