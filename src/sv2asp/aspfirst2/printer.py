"""Print an ASP-first design as SystemVerilog.

WIDTH POLICY (the load-bearing decision -- risk R1 of the plan). SystemVerilog sizes an operand
by its CONTEXT (the widest operand and the assignment target together), so a nested expression
printed inline can be evaluated at a width the author never wrote. Every non-leaf operand is
therefore printed as its OWN typed wire (`<lhs>__eK`, SSA), so each `assign` is `leaf op leaf`
whose context width is exactly the ASP term's `W` (the lint guarantees operands are no wider
than their op, and a def's width equals its net's). Where SV would sign-extend on its own
(`sext`, `ashr`, signed compares/division) the operand is first widened to the op width by an
explicit zero-extending wire, so the sign bit is the one the `@func` reads.

STATE. `--mode behav` prints `always_ff` blocks with the shape the translator recognises for an
async-reset register (`if (!rst) q <= RV; else if (en) q <= d;`); `--mode cells` instantiates the
`FF` / `ARFF` cells of `lib/aspfirst/cells_sim.sv` (same interfaces as
`examples/rtl2asp/primitives_demo/stubs/cells.sv`, with behavioural bodies so Icarus can run them; sv2asp
lowers them from its registry by NAME). A memory (`spram`) is always behavioural. An ENUM-typed
register is always behavioural (a `logic` cell port cannot drive an enum variable without a
cast; the tag is what the ASP carries).

GUARDED RULES. A net defined by comb rules becomes an `always_comb` if/else-if chain, one arm per
rule in authoring order. The LAST arm is printed as a bare `else` only when the arms are PROVEN
total for that head (`totality_certificate` -- a static clingo check with the guarded signals
free over their domains); otherwise every arm keeps its condition and there is no default, so a
missing case reaches sv2asp as an incomplete `always_comb` and fails LOUDLY there instead of
becoming a silent latch or an invented value."""
