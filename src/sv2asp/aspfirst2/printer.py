def stub_sv(module_path) -> str:
    """An INTERFACE STUB for an authored module: its port list and an empty body -- the shape of
    `examples/rtl2asp/primitives_demo/stubs/cells.sv`. What a parent's RTL is printed against when
    the module is still abstract (contract-only): the parent is real RTL, the child a black box the
    user builds later against the same contract."""
    from .load import load
    d = load(module_path)
    pw = (lambda p: d.raw.port_w.get(p.name, p.width)) if d.raw is not None else (lambda p: p.width)
    ports = ",\n".join(f"  {p.direction} {_wdecl(pw(p))} {p.name}" for p in d.ports)
    numeric, hdr_derived, _body = _split_params(d, d.raw)
    plist = ([f"  parameter {k.upper()} = {v}" for k, v in numeric]
             + [f"  localparam {k.upper()} = {_wtxt(v)}" for k, v in hdr_derived])
    hdr = (f"module {d.name} #(\n" + ",\n".join(plist) + "\n) (\n") if plist else f"module {d.name} (\n"
    return (f"// STUB (interface only) of {d.name}: abstract in the parent -- its contract "
            f"({module_path.stem}.contract.lp) is what the parent was proven against.\n"
            f"{hdr}{ports}\n);\nendmodule\n")


def print_hier(path, mode: str = "behav") -> str:
    """The design at `path` and every authored module it (transitively) instantiates, each as its
    own SystemVerilog module -- children first, so a single file compiles. A module that is
    ABSTRACT in its parent is emitted as an interface stub (the parent's RTL alone, the child a
    black box); abstract NETS refuse."""
    from .compose import compose, resolve_module
    from .load import load
    comp = compose(path)
    if comp.design.abstract_nets() and not any(ab for _, _, ab in comp.tree):
        raise PrintError(f"still abstract: {', '.join(comp.design.abstract_nets())} -- refine before printing")
    texts, seen = [], set()

    def emit(p, top: bool):
        d = load(p)
        if d.abstract_nets():
            raise PrintError(f"{p.name}: abstract net(s) {', '.join(d.abstract_nets())} -- refine before printing")
        abstract_insts = set(d.abstract_insts())
        for i in d.module_insts():
            if i.cell in seen:
                continue
            seen.add(i.cell)
            mp = resolve_module(i.cell, pathlib.Path(p).parent)
            if i.name in abstract_insts:
                texts.append(stub_sv(mp))
            else:
                emit(mp, False)
        texts.append(print_sv(d, mode=mode, src=str(p)))
    emit(pathlib.Path(path), True)
    return "\n".join(texts)
